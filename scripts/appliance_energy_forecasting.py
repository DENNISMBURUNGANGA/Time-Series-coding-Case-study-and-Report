    if c == BEST_BENCH: continue
    dm, p = diebold_mariano(forecasts[c].values - test.values, e_bench)
    verdict = "significantly better" if (dm < 0 and p < .05) else \
              "significantly worse"  if (dm > 0 and p < .05) else "not distinguishable"
