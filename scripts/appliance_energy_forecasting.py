"""---
# Parts 5 & 6 — Feature Engineering and Machine Learning

## The leakage guard

Every target-derived feature uses a lag `>= HORIZON`. Rolling statistics are
shifted by `HORIZON`, not by 1. The cell after the feature builder **proves** the
guard works by mutating the future and checking no training-period feature moves.

## Two feature sets, deliberately

| Set | Contents | Interpretation |
|---|---|---|
| **`true`** | calendar features + target lags/rollings (≥24 h) | A genuine 24-hour-ahead forecast. Everything is knowable at the origin. |
| **`conditional`** | the above **plus realised indoor sensors and outdoor weather at the forecast timestamp** | A *conditional* forecast. It answers "what would energy use be, given perfect knowledge of tomorrow's weather and indoor conditions?" — not "what will it be?" |

Running both and reporting the gap is the direct, quantified answer to report
questions 3 and 5, and it is the analysis that separates this report from one
that simply asserts covariates help.
"""

# =====================================================================
# FEATURE ENGINEERING (leakage-safe by construction)
# =====================================================================
LAGS     = [l for l in [24, 25, 26, 27, 48, 72, 96, 168, 169, 192] if l >= MIN_TARGET_LAG]
WINDOWS  = [3, 6, 12, 24, 48, 168]

assert min(LAGS) >= MIN_TARGET_LAG, "lag shorter than the horizon would leak"

# Define OUTDOOR first, then exclude it from INDOOR.
#
# Selecting indoor sensors by prefix alone is wrong: RH_out starts with "RH_"
# but is an outdoor reading, so it lands in both lists and produces a duplicate
# column when they are joined. The assertion below makes that failure loud
# rather than silent.
OUTDOOR = [c for c in ["T_out", "Press_mm_hg", "RH_out", "Windspeed",
                       "Visibility", "Tdewpoint"] if c in hourly.columns]

INDOOR = [c for c in hourly.columns
          if (c.startswith("T") or c.startswith("RH_"))
          and c not in OUTDOOR
          and c != TARGET]

assert not set(INDOOR) & set(OUTDOOR), \
    f"column in both groups: {sorted(set(INDOOR) & set(OUTDOOR))}"

def build_features(df, target=TARGET, horizon=HORIZON):
    out = pd.DataFrame(index=df.index)

    # -- calendar: known at any origin, arbitrarily far ahead ---------
    out["hour"]       = df.index.hour
    out["dayofweek"]  = df.index.dayofweek
    out["is_weekend"] = (df.index.dayofweek >= 5).astype(int)
    out["hour_sin"]   = np.sin(2*np.pi*out["hour"]/24)
    out["hour_cos"]   = np.cos(2*np.pi*out["hour"]/24)
    out["dow_sin"]    = np.sin(2*np.pi*out["dayofweek"]/7)
    out["dow_cos"]    = np.cos(2*np.pi*out["dayofweek"]/7)

    # -- target history: every lag >= horizon ------------------------
    s = df[target]
    for L in LAGS:
        out[f"lag_{L}"] = s.shift(L)
    for w in WINDOWS:
        base = s.shift(horizon)          # shift by horizon, NOT by 1
        out[f"roll_mean_{w}"] = base.rolling(w).mean()
        out[f"roll_std_{w}"]  = base.rolling(w).std()
        out[f"roll_min_{w}"]  = base.rolling(w).min()
        out[f"roll_max_{w}"]  = base.rolling(w).max()

    return out

CAL_COLS = ["hour","dayofweek","is_weekend","hour_sin","hour_cos","dow_sin","dow_cos"]
