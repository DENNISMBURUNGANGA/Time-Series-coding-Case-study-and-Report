def diebold_mariano(e1, e2, h=HORIZON, power=1):
    """H0: the two forecasts have equal expected loss.
    Newey-West variance with h-1 lags, Harvey small-sample correction."""
    d = np.abs(e1)**power - np.abs(e2)**power
    n = len(d); dbar = d.mean()
    gamma0 = np.sum((d - dbar)**2) / n
    var = gamma0
    for k in range(1, h):
        gk = np.sum((d[k:] - dbar) * (d[:-k] - dbar)) / n
        var += 2 * (1 - k/h) * gk
    dm = dbar / np.sqrt(var / n)
    corr = np.sqrt((n + 1 - 2*h + h*(h-1)/n) / n)
    dm *= corr
    p = 2 * (1 - stats.t.cdf(abs(dm), df=n-1))
    return dm, p

